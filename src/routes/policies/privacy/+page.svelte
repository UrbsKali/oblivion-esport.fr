	<h1>Politique de confidentialité</h1>

	<h2>ARTICLE 1 : PRÉAMBULE</h2>
	<p>La présente politique de confidentialité a pour but d'informer les utilisateurs du site :</p>
	<ul>
		<li>
			Sur la manière dont sont collectées leurs données personnelles. Sont considérées comme des
			données personnelles, toute information permettant d'identifier un utilisateur. A ce titre, il
			peut s'agir : de ses noms et prénoms, de son âge, de son adresse email, de sa localisation ou
			encore de son adresse IP (liste non-exhaustive) ;
		</li>
		<li>Sur les droits dont ils disposent concernant ces données ;</li>
		<li>
			Sur la personne responsable du traitement des données à caractère personnel collectées et
			traitées ;
		</li>
		<li>Sur les destinataires de ces données personnelles ;</li>
		<li>Sur la politique du site en matière de cookies.</li>
	</ul>
	<p>
		Cette politique complète les mentions légales et les Conditions Générales d'Utilisation
		consultables par les utilisateurs via ces liens : <a href="/policies/cgu">CGU</a>,
		<a href="/policies/legal">Mentions légales</a>
		.
	</p>

	<h2>ARTICLE 2 : PRINCIPES RELATIFS À LA COLLECTE ET AU TRAITEMENT DES DONNÉES PERSONNELLES</h2>
	<p>
		Conformément à l'article 5 du Règlement européen 2016/679, les données à caractère personnel
		sont :
	</p>
	<ul>
		<li>Traitées de manière licite, loyale et transparente au regard de la personne concernée ;</li>
		<li>
			Collectées pour des finalités déterminées (cf. Article 3.1 des présentes), explicites et
			légitimes, et ne pas être traitées ultérieurement d'une manière incompatible avec ces
			finalités ;
		</li>
		<li>
			Adéquates, pertinentes et limitées à ce qui est nécessaire au regard des finalités pour
			lesquelles elles sont traitées ;
		</li>
		<li>
			Exactes et, si nécessaire, tenues à jour. Toutes les mesures raisonnables doivent être prises
			pour que les données à caractère personnel qui sont inexactes, eu égard aux finalités pour
			lesquelles elles sont traitées, soient effacées ou rectifiées sans tarder ;
		</li>
		<li>
			Conservées sous une forme permettant l'identification des personnes concernées pendant une
			durée n'excédant pas celle nécessaire au regard des finalités pour lesquelles elles sont
			traitées ;
		</li>
		<li>
			Traitées de façon à garantir une sécurité appropriée des données collectées, y compris la
			protection contre le traitement non autorisé ou illicite et contre la perte, la destruction ou
			les dégâts d'origine accidentelle, à l'aide de mesures techniques ou organisationnelles
			appropriées.
		</li>
	</ul>
	<p>
		Le traitement n'est licite que si, et dans la mesure où, au moins une des conditions suivantes
		est remplie :
	</p>
	<ul>
		<li>
			La personne concernée a consenti au traitement de ses données à caractère personnel pour une
			ou plusieurs finalités spécifiques ;
		</li>
		<li>
			Le traitement est nécessaire à l'exécution d'un contrat auquel la personne concernée est
			partie ou à l'exécution de mesures précontractuelles prises à la demande de celle-ci ;
		</li>
		<li>
			Le traitement est nécessaire au respect d'une obligation légale à laquelle le responsable du
			traitement est soumis ;
		</li>
		<li>
			Le traitement est nécessaire à la sauvegarde des intérêts vitaux de la personne concernée ou
			d'une autre personne physique ;
		</li>
		<li>
			Le traitement est nécessaire à l'exécution d'une mission d'intérêt public ou relevant de
			l'exercice de l'autorité publique dont est investi le responsable du traitement ;
		</li>
		<li>
			Le traitement est nécessaire aux fins des intérêts légitimes poursuivis par le responsable du
			traitement ou par un tiers, à moins que ne prévalent les intérêts ou les libertés et droits
			fondamentaux de la personne concernée qui exigent une protection des données à caractère
			personnel, notamment lorsque la personne concernée est un enfant.
		</li>
	</ul>

	<h2>
		ARTICLE 3 : DONNÉES À CARACTÈRE PERSONNEL COLLECTÉES ET TRAITÉES DANS LE CADRE DE LA NAVIGATION
		SUR LE SITE
	</h2>

	<h3>Article 3.1 : Données collectées</h3>
	<p>Les données personnelles collectées dans le cadre de notre activité sont les suivantes :</p>
	<ul>
		<li>Nom d'utilisateur</li>
		<li>Adresse email</li>
		<li>Adresse IP</li>
		<li>Données de connexion</li>
		<li>Lien avec d'autre service (Discord, etc)</li>
		<li>Toutes informations lié aux tournois organisés par Oblivion</li>
		<li>Données de navigation</li>
	</ul>
	<p>La collecte et le traitement de ces données répond à la (aux) finalité(s) suivante(s) :</p>
	<ul>
		<li>Création et gestion de compte</li>
		<li>Organisation de tournois</li>
		<li>Communication avec les utilisateurs</li>
		<li>Amélioration de l'expérience utilisateur</li>
	</ul>

	<h3>Article 3.2 : Mode de collecte des données</h3>
	<p>Lorsque vous utilisez notre site, sont automatiquement collectées les données suivantes :</p>
	<ul>
		<li>Adresse IP</li>
		<li>Données de connexion</li>
		<li>Données de navigation</li>
	</ul>
	<p>
		D'autres données personnelles sont collectées lorsque vous effectuez les opérations suivantes
		sur la plateforme :
	</p>
	<ul>
		<li>Création de compte</li>
		<li>Participation à un tournoi</li>
		<li>Communication avec l'équipe d'Oblivion</li>
		<li>Connexion avec un service externe (Discord, etc)</li>
	</ul>
	<p>
		Elles sont conservées par le responsable du traitement dans des conditions raisonnables de
		sécurité, pour une durée de deux ans depuis la dernière connexion. La suppression des données
		sera automatique et disposera d'un préavis de deux semaines. Les données personnelles collectées
		ne sont ni cédées ni vendues à des tiers, sauf en cas de fusion ou de cession de l'association.
	</p>
	<p>
		La société est susceptible de conserver certaines données à caractère personnel au-delà des
		délais annoncés ci-dessus afin de remplir ses obligations légales ou réglementaires.
	</p>

